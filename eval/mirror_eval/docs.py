"""Generated dossier pages. CAPABILITIES, CLAIMS_TO_EVIDENCE, SOURCE_REGISTER and RESULTS are
rendered from the same Python objects the export uses, so the docs cannot drift from the data.
Regenerate with: uv run python -m mirror_eval docs
"""
from __future__ import annotations

from pathlib import Path

from . import capabilities as caps
from . import registry
from .agent import SUBJECT_AGENTS
from .export import discover_runs
from .paths import DOCS_ROOT, RUNS_ROOT
from .runner import build_run
from .schema import Metric

HEADER = "<!-- GENERATED by `uv run python -m mirror_eval docs`. Do not edit by hand. -->\n\n"


def _cell(x) -> str:
    if x is None:
        return "pending"
    if isinstance(x, (list, tuple)):
        return "<br>".join(_cell(i) for i in x) if x else "none"
    return str(x).replace("|", "\\|").replace("\n", " ") or "none"


def _table(headers: list[str], rows: list[list]) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "|".join(" --- " for _ in headers) + "|"]
    out += ["| " + " | ".join(_cell(c) for c in row) + " |" for row in rows]
    return "\n".join(out) + "\n"


def _metric(m: Metric) -> str:
    if m.status == "unavailable":
        return f"unavailable ({m.reason})"
    ci = f", 95% CI {m.ci_low:.3f} to {m.ci_high:.3f}" if m.ci_low is not None else ""
    n = f", n={m.n}" if m.n is not None else ""
    return f"{m.value:.3f} {m.unit}{n}{ci}"


def capabilities_md() -> str:
    rows = [[c.id, c.area, c.name, c.status, c.entry_point or "none", c.task_count,
             "null" if c.passed is None else c.passed, "null" if c.failed is None else c.failed,
             c.evidence_refs, c.note] for c in caps.capabilities()]
    return (HEADER + "# Capabilities\n\n"
            "What exists in the repo today. Status describes the code, not an agent's measured performance. "
            "`passed` and `failed` stay null until a subject-agent run exists. Engine unit tests are not agent "
            "evaluations and never fill those columns.\n\n"
            + _table(["id", "area", "capability", "status", "entry point", "tasks", "passed", "failed",
                      "evidence", "note"], rows))


def claims_md() -> str:
    rows = [[c.id, c.claim, c.status, "yes" if c.demo_allowed else "NO", c.evidence_refs,
             caps.CLAIM_NOTES.get(c.id, "")] for c in caps.claims()]
    return (HEADER + "# Claims to evidence\n\n"
            "Every claim the demo might want to make, and what backs it today. A claim that is not "
            "`demo_allowed` must not appear in the demo, on a slide or in a voiceover. `untested` with an engine "
            "test reference means the deterministic engine shows the behavior in unit tests. That is engine-level, "
            "not agent-level.\n\n"
            + _table(["id", "claim", "status", "demo allowed", "evidence", "what it would take"], rows))


def source_register_md() -> str:
    parts = [HEADER + "# Source register\n\n"
             "Generated from `eval/registry/suites.json`. `pending` means nobody has verified the field against "
             "the source yet. Do not fill a pending field from memory.\n\n"]
    suites = registry.load_suites()
    parts.append(_table(
        ["id", "layer", "provenance", "protocol", "access", "revision", "checked at", "license", "split", "tasks"],
        [[s.id, s.layer, s.provenance, s.protocol, s.access, s.revision, s.revision_checked_at, s.license,
          s.split, s.task_count] for s in suites]))
    for s in suites:
        parts.append(f"\n## {s.id}\n\n{s.name}\n\n"
                     f"- owner: {s.owner}\n- access: {s.access} ({s.access_note or 'no note'})\n"
                     f"- source urls: {', '.join(s.source_urls) or 'pending'}\n"
                     f"- native metric: {s.native_metric}"
                     + (f" ({s.native_metric_note})" if s.native_metric_note else "") + "\n"
                     f"- families: {', '.join(f'{f.id} ({f.task_count})' for f in s.families) or 'none'}\n"
                     "- a result on this suite must NOT be called anything these rule out:\n"
                     + "".join(f"  - {r}\n" for r in s.restrictions))
    return "".join(parts)


def results_md(runs_root: Path = RUNS_ROOT) -> str:
    loaded = discover_runs(runs_root)
    subject = [(m, r) for m, r in loaded if m["system"]["kind"] != "ORACLE_SMOKE"]
    oracle = [(m, r) for m, r in loaded if m["system"]["kind"] == "ORACLE_SMOKE"]
    parts = [HEADER + "# Results\n\n"]
    parts.append(f"Registered subject agents: {', '.join(sorted(SUBJECT_AGENTS)) or 'none'}.\n\n## Subject-agent runs\n\n")
    if not subject:
        parts.append("No subject-agent runs exist. There is no agent performance number of any kind, on any suite. "
                     "Anything that looks like one is a layout sample or an oracle smoke check.\n")
    for m, r in subject:
        run = build_run(m, r)
        parts.append(f"### {run.id}\n\n- system: {run.system_id}\n- suite: {run.suite_id}\n- execution: {run.execution}\n"
                     f"- whole-task success: {_metric(run.whole_task_success)}\n"
                     f"- pass@1: {_metric(run.pass_at_1)}\n- success on all k: {_metric(run.pass_all_of_k)}\n"
                     f"- correct escalation rate: {_metric(run.correct_escalation_rate)}\n"
                     f"- invalid actions accepted: {_metric(run.invalid_actions_accepted)}\n"
                     f"- incidents: {len(run.incidents)}\n- reproduce: `{run.reproduce}`\n\n")
    parts.append("\n## Grader checks (oracle smoke, not results)\n\n"
                 "The oracle builds gold final states from private truth. A clean oracle run shows that the grader "
                 "accepts a correct state and that the runner works end to end. It says nothing about any agent.\n\n")
    if not oracle:
        parts.append("No oracle smoke run found. Run `uv run python -m mirror_eval selftest`.\n")
    for m, r in oracle:
        run = build_run(m, r)
        o = run.outcomes
        parts.append(f"- {run.id}: kind ORACLE_SMOKE, mode {run.mode}, {run.n_tasks} tasks, "
                     f"{o.n_pass} pass, {o.n_correct_escalation} correct_escalation, "
                     f"{o.n_fail + o.n_partial + o.n_waiting + o.n_error} anything else. Grader check only.\n")
    return "".join(parts)


GENERATED = {
    "CAPABILITIES.md": capabilities_md,
    "CLAIMS_TO_EVIDENCE.md": claims_md,
    "SOURCE_REGISTER.md": source_register_md,
    "RESULTS.md": results_md,
}


def write_docs(docs_root: Path = DOCS_ROOT) -> list[Path]:
    docs_root.mkdir(parents=True, exist_ok=True)
    written = []
    for name, render in GENERATED.items():
        path = docs_root / name
        path.write_text(render())
        written.append(path)
    return written
